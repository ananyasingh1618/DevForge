#!/usr/bin/env node
/**
 * Human-reviewable per-case retrieval relevance report (Phase 13, Milestone
 * 13.5 — see docs/BENCHMARK_EXPANSION_PHASE_PLAN.md). For every retrieval
 * case, shows the query, expected direct/supporting sources, the top-5
 * actually-returned sources with their full score breakdown (semantic/
 * lexical/identifier/file-path/combined), each source's relevance label,
 * whether it was a near-duplicate, and whether the adaptive cutoff removed
 * it from the final selection — enough for a developer to tell apart a
 * ranking problem, a bad relevance label, a bad chunking decision, a
 * missing indexed source, a query-understanding problem, and a benchmark-
 * design problem without re-deriving any of it by hand.
 *
 * Deterministic, no credentials, no network. `pnpm relevance:report` writes
 * evaluation/reports/relevance-report.md.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FIXTURE_CHUNKS } from "./dataset/fixtureRepo.js";
import { RETRIEVAL_CASES, type RetrievalCase } from "./dataset/retrievalCases.js";
import { rankChunks, gradedCase, relevanceGrade, TOP_K } from "./evaluators/retrievalEvaluator.js";
import { rankWithDiagnostics } from "./diagnostics.js";

const REPORTS_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "reports");
const TOP_N_SHOWN = 5;

type DiagnosisHint =
  | "pass"
  | "ranking-problem"
  | "missing-indexed-source"
  | "benchmark-design (deliberately ambiguous query)"
  | "query-understanding-problem";

function diagnose(testCase: RetrievalCase, hit: boolean, firstRelevantRank: number | null): DiagnosisHint {
  const graded = gradedCase(testCase);
  if (!graded.answerable) return "pass";
  if (hit) return "pass";
  if (graded.category === "vague-wording") return "benchmark-design (deliberately ambiguous query)";
  const realChunkIds = new Set(FIXTURE_CHUNKS.map((c) => c.chunkId));
  if (testCase.expectedChunkIds.some((id) => !realChunkIds.has(id))) return "missing-indexed-source";
  if (firstRelevantRank !== null && firstRelevantRank <= FIXTURE_CHUNKS.length / 2) return "ranking-problem";
  return "query-understanding-problem";
}

async function renderCase(testCase: RetrievalCase): Promise<string> {
  const graded = gradedCase(testCase);
  const returned = await rankChunks(testCase.query, FIXTURE_CHUNKS, TOP_K);
  const returnedIds = new Set(returned.map((r) => r.chunk.chunkId));
  const full = await rankWithDiagnostics(testCase.query);
  const breakdown = full.slice(0, TOP_N_SHOWN);
  const hit = returned.some((r) => testCase.expectedChunkIds.includes(r.chunk.chunkId));
  const firstRelevantRank = (() => {
    const found = full.find((d) => testCase.expectedChunkIds.includes(d.chunkId));
    return found ? found.rank : null;
  })();

  const rows = breakdown
    .map((d) => {
      const grade = relevanceGrade(d.chunkId, graded.direct, graded.supporting);
      const label = grade === 2 ? "direct" : grade === 1 ? "supporting" : "irrelevant";
      const inFinalSelection = returnedIds.has(d.chunkId);
      return (
        `| ${d.rank} | \`${d.chunkId}\` | ${label} | ${d.signals.semanticScore.toFixed(3)} | ` +
        `${d.signals.lexicalScore.toFixed(3)} | ${d.signals.identifierScore.toFixed(3)} | ` +
        `${d.signals.filePathScore.toFixed(3)} | ${d.combinedScore.toFixed(3)} | ` +
        `${d.duplicateGroup !== null ? "yes" : "no"} | ${inFinalSelection ? "kept" : "cut by adaptive cutoff"} |`
      );
    })
    .join("\n");

  return `## ${testCase.id}

- **Query**: ${testCase.query}
- **Category**: ${graded.category} | **Language**: ${graded.language} | **Difficulty**: ${graded.difficulty} | **Answerable**: ${graded.answerable}
- **Direct sources**: ${graded.direct.length > 0 ? graded.direct.map((id) => `\`${id}\``).join(", ") : "_none (insufficient-evidence case)_"}
- **Supporting sources**: ${graded.supporting.length > 0 ? graded.supporting.map((id) => `\`${id}\``).join(", ") : "_none_"}
- **Result**: ${hit || !graded.answerable ? "✅ hit" : "❌ miss"} — first relevant source ranked ${firstRelevantRank ?? "not in top " + FIXTURE_CHUNKS.length}
- **Diagnosis**: ${diagnose(testCase, hit, firstRelevantRank)}

| Rank | Chunk | Relevance | Semantic | Lexical | Identifier | File path | Combined | Duplicate? | In final selection? |
|---|---|---|---|---|---|---|---|---|---|
${rows}
`;
}

async function main() {
  const sections = (await Promise.all(RETRIEVAL_CASES.map(renderCase))).join("\n---\n\n");
  const markdown = `# DevForge Retrieval Relevance Report

Per-case, human-reviewable breakdown of every retrieval case's top ${TOP_N_SHOWN} ranked candidates
— generated by \`pnpm relevance:report\`. Deterministic (a real local embedding model with no
randomness at inference time — see localEmbedding.ts), no credential, no hosted API call; a
network fetch happens only once, to download the local model on a genuinely cold cache. See
docs/BENCHMARK_EXPANSION_PHASE_PLAN.md (Milestone 13.5) for how to read the **Diagnosis** column:
it distinguishes a ranking problem (the right chunk exists and is chunked correctly, just ranked
too low), a missing indexed source (the expected chunk id doesn't exist at all — should never
happen; the benchmark audit already catches this), a benchmark-design issue (the query is
deliberately ambiguous, e.g. the \`vague-wording\` category), and a general query-understanding
problem (the right chunk ranked very low or not at all, with no simpler explanation).

Total cases: ${RETRIEVAL_CASES.length}

---

${sections}
`;

  console.log(`Generated relevance report for ${RETRIEVAL_CASES.length} cases.`);
  mkdirSync(REPORTS_DIR, { recursive: true });
  const outPath = path.join(REPORTS_DIR, "relevance-report.md");
  writeFileSync(outPath, markdown);
  console.log(`Report written to: ${outPath}`);
}

main().catch((err: unknown) => {
  console.error("relevance:report failed:", err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
